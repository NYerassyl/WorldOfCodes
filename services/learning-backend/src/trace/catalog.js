import { readFileSync } from "node:fs";

const LEVEL_DIFFICULTIES = ["easy", "easy-medium", "medium", "medium-hard", "hard"];
const catalog = [];
const ids = new Set();

for (let level = 1; level <= 5; level += 1) {
  // Single source of truth: the original 50 FastAPI exercise JSON entries.
  // Do not duplicate the code, answers, or English explanations in Node.
  const file = new URL(
    `../../../fastapi-backend/trace/catalog/level${level}.json`,
    import.meta.url,
  );
  const exercises = JSON.parse(readFileSync(file, "utf8"));
  if (!Array.isArray(exercises) || exercises.length !== 10) {
    throw new Error(`Expected exactly 10 Python Trace exercises in level ${level}`);
  }
  for (const exercise of exercises) {
    if (
      exercise.level !== level ||
      exercise.difficulty !== LEVEL_DIFFICULTIES[level - 1] ||
      typeof exercise.id !== "string" ||
      typeof exercise.title !== "string" ||
      typeof exercise.topic !== "string" ||
      typeof exercise.instructions !== "string" ||
      typeof exercise.code !== "string" ||
      typeof exercise.expected_stdout !== "string" ||
      typeof exercise.explanation !== "string" ||
      ids.has(exercise.id)
    ) {
      throw new Error(`Invalid or duplicated Python Trace exercise in level ${level}`);
    }
    ids.add(exercise.id);
    catalog.push(Object.freeze(exercise));
  }
}

const exerciseById = new Map(catalog.map((exercise) => [exercise.id, exercise]));

export const TRACE_DIFFICULTIES = Object.freeze([...LEVEL_DIFFICULTIES]);

export function traceSummary(exercise) {
  const { id, level, difficulty, topic, title } = exercise;
  return { id, level, difficulty, topic, title };
}

export function traceDetail(exercise) {
  const { instructions, code } = exercise;
  return { ...traceSummary(exercise), instructions, code };
}

export function listTraceExercises({ level, difficulty, topic } = {}) {
  return catalog
    .filter(
      (exercise) =>
        (level === undefined || exercise.level === level) &&
        (difficulty === undefined || exercise.difficulty === difficulty) &&
        (topic === undefined || exercise.topic.toLowerCase() === topic.toLowerCase()),
    )
    .map(traceSummary);
}

export function findTraceExercise(id) {
  return exerciseById.get(id) ?? null;
}

export function normalizeTraceOutput(output) {
  // Players are not expected to type the final newline generated by print().
  // All internal spaces and newlines remain significant, like the Python API.
  return output.replace(/\r\n/g, "\n").replace(/\n$/, "");
}

export function gradeTraceOutput(exercise, output) {
  const submittedOutput = normalizeTraceOutput(output);
  const expectedOutput = normalizeTraceOutput(exercise.expected_stdout);
  return {
    correct: submittedOutput === expectedOutput,
    submittedOutput,
    expectedOutput,
  };
}
